const norm = (s = '') => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().trim();

export const getPlantaById = (id) => PLANTAS.find((p) => p.id === id);

/**
 * Busca info medicinal: especie exacta → mismo género → familia → null.
 */
export const buscarInfoMedicinal = (cientifico = '', familia = '') => {
  const nombre = norm(cientifico);
  const exacta = PLANTAS.find((p) => norm(p.cientifico) === nombre);
  if (exacta) return { nivel: 'especie', planta: exacta };

  const genero = nombre.split(' ')[0];
  const delGenero = PLANTAS.find((p) => norm(p.cientifico).split(' ')[0] === genero);
  if (delGenero) return { nivel: 'genero', planta: delGenero };

  const fam = Object.keys(FAMILIAS).find((f) => norm(f) === norm(familia));
  if (fam) return { nivel: 'familia', familia: fam, texto: FAMILIAS[fam] };

  return null;
};
